class Smartphone:

        def __init__(self, model, mark, number):
                self.model = model
                self.mark = mark
                self.number = number

def get_model(self):
        return self.model

def get_mark(self):
        return self.mark

def get_number(self):
        return self.number

def get_Smartphone_info(self):
        return f"Модель: {self.model}, Марка: {self.mark}, Номер телефона: {self.number}"